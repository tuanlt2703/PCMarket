CREATE TABLE models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_type_id BIGINT NOT NULL REFERENCES component_types(id),
    manufacturer_id BIGINT REFERENCES manufacturers(id),
    model_name VARCHAR(200) NOT NULL,
    description TEXT,
    release_date DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (component_type_id, manufacturer_id, model_name)
);

CREATE INDEX idx_models_component_type_id ON models(component_type_id);
CREATE INDEX idx_models_manufacturer_id ON models(manufacturer_id);
CREATE INDEX idx_models_model_name ON models(model_name);
